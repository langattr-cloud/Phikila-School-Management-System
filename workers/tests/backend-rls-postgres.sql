DO $$
DECLARE
  table_name text;
BEGIN
  FOREACH table_name IN ARRAY ARRAY[
    'finance_supplier_invoices','finance_supplier_payments','finance_capitation_templates',
    'finance_capitation_vote_heads','finance_capitation_receipts','finance_capitation_allocations',
    'finance_capitation_expenditure','timetable_teacher_profiles','tt_timetable_ribbon_workspace_revisions'
  ]
  LOOP
    IF has_table_privilege('anon',format('public.%I',table_name),'SELECT')
       OR has_table_privilege('authenticated',format('public.%I',table_name),'SELECT') THEN
      RAISE EXCEPTION 'Browser access remains on public.%',table_name;
    END IF;
    IF NOT has_table_privilege('service_role',format('public.%I',table_name),'SELECT') THEN
      RAISE EXCEPTION 'service_role cannot read public.%',table_name;
    END IF;
  END LOOP;
  IF has_sequence_privilege('anon','public.streams_id_seq','USAGE')
     OR NOT has_sequence_privilege('authenticated','public.streams_id_seq','USAGE')
     OR NOT has_sequence_privilege('service_role','public.streams_id_seq','USAGE') THEN
    RAISE EXCEPTION 'Unexpected streams identity sequence privileges';
  END IF;
END $$;

