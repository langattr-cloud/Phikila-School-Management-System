DO $$
DECLARE
  v_copy uuid;
  v_library_copy uuid;
  v_count integer;
  v_status text;
  v_teacher integer;
  v_student integer;
BEGIN
  SELECT count(*) INTO v_count FROM public.library_book_copies WHERE book_id=1;
  IF v_count <> 3 THEN RAISE EXCEPTION 'Expected 3 numbered legacy copies; found %', v_count; END IF;
  IF EXISTS (SELECT 1 FROM public.library_book_copies WHERE book_id=1 AND status <> 'unreconciled') THEN
    RAISE EXCEPTION 'Legacy copies with unknown physical assignment must remain unreconciled';
  END IF;
  SELECT count(*) INTO v_count FROM public.library_book_copies WHERE book_id=2 AND status='available';
  IF v_count <> 2 THEN RAISE EXCEPTION 'Expected 2 available copies; found %', v_count; END IF;

  SELECT id INTO v_copy FROM public.library_book_copies WHERE book_id=1 AND copy_number='01/03';
  PERFORM public.move_library_book_copy(v_copy,'reconcile_copy',101,'Teacher A','good',null,'Physically verified with teacher',null,'teacher');
  PERFORM public.move_library_book_copy(v_copy,'issue_to_student',201,'Student A','good',current_date+14,'Issued by Teacher A',null,null);

  -- A student may only return the copy to the teacher who issued it.
  BEGIN
    PERFORM public.move_library_book_copy(v_copy,'student_return_to_teacher',102,'Teacher B','good',null,'Wrong teacher',null,null);
    RAISE EXCEPTION 'A student return to a different teacher was unexpectedly accepted';
  EXCEPTION WHEN check_violation THEN NULL;
  END;
  IF (SELECT current_holder_id FROM public.library_book_copies WHERE id=v_copy) <> 201 THEN
    RAISE EXCEPTION 'Rejected return changed the copy holder';
  END IF;

  PERFORM public.move_library_book_copy(v_copy,'student_return_to_teacher',101,'Teacher A','good',null,'Returned to issuing teacher',null,null);
  PERFORM public.move_library_book_copy(v_copy,'issue_to_student',201,'Student A','good',current_date+14,'Re-issued by Teacher A',null,null);
  PERFORM public.move_library_book_copy(v_copy,'mark_lost',null,null,'lost',null,'Reported lost by student',null,null);

  SELECT accountable_teacher_id, student_id INTO v_teacher,v_student
  FROM public.library_teacher_accountability WHERE copy_id=v_copy;
  IF v_teacher <> 101 OR v_student <> 201 THEN
    RAISE EXCEPTION 'Lost student-held copy no longer reports teacher accountability';
  END IF;

  SELECT id INTO v_library_copy FROM public.library_book_copies WHERE book_id=2 AND copy_number='01/02';
  PERFORM public.set_library_copy_preissue_exclusion(v_library_copy,'exclude_before_issue','Missing during physical stocktake',null);
  SELECT status INTO v_status FROM public.library_book_copies WHERE id=v_library_copy;
  IF v_status <> 'excluded' THEN RAISE EXCEPTION 'Pre-issue exclusion did not set excluded status'; END IF;
  PERFORM public.set_library_copy_preissue_exclusion(v_library_copy,'restore_excluded_copy','Copy located and verified',null);
  SELECT status INTO v_status FROM public.library_book_copies WHERE id=v_library_copy;
  IF v_status <> 'available' THEN RAISE EXCEPTION 'Pre-issue restoration did not restore available status'; END IF;

  -- Movement history cannot be rewritten.
  BEGIN
    UPDATE public.library_copy_movements SET notes='tampered' WHERE copy_id=v_copy;
    RAISE EXCEPTION 'Movement history update was unexpectedly accepted';
  EXCEPTION WHEN check_violation THEN NULL;
  END;

  IF (SELECT count(*) FROM public.library_copy_movements WHERE copy_id=v_copy) <> 5 THEN
    RAISE EXCEPTION 'Expected five append-only movements for custody chain';
  END IF;
  IF (SELECT count(*) FROM public.library_copy_movements WHERE copy_id=v_library_copy) <> 2 THEN
    RAISE EXCEPTION 'Expected two immutable movements for exclusion and restoration';
  END IF;
END $$;

