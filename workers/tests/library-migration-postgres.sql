CREATE TABLE public.library_books (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  author text,
  isbn text,
  category text,
  shelf_location text,
  total_copies integer,
  available_copies integer,
  status text,
  created_at timestamptz NOT NULL DEFAULT now(),
