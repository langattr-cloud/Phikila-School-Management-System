  (1, 1001, NULL, 20.00, 'CREDIT');
COMMIT;

DO $$
DECLARE
  v_journal_id bigint;
  v_debits numeric;
  v_credits numeric;
  v_receipts integer;
BEGIN
  SELECT journal_id INTO v_journal_id FROM public.payments WHERE id = 1001;
  IF v_journal_id IS NULL THEN RAISE EXCEPTION 'payment was not linked to a journal'; END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.finance_journals
    WHERE id = v_journal_id AND school_id = 1 AND status = 'POSTED'
  ) THEN RAISE EXCEPTION 'posted school-scoped journal missing'; END IF;
  SELECT sum(debit), sum(credit) INTO v_debits, v_credits
  FROM public.finance_journal_entries WHERE journal_id = v_journal_id;
  IF abs(coalesce(v_debits,0) - coalesce(v_credits,0)) > 0.005
    THEN RAISE EXCEPTION 'journal is unbalanced: debit %, credit %', v_debits, v_credits; END IF;
  SELECT count(*) INTO v_receipts FROM public.finance_receipts
  WHERE payment_id = 1001 AND school_id = 1 AND student_id = 101 AND abs(amount - 100) <= 0.005;
  IF v_receipts <> 1 THEN RAISE EXCEPTION 'expected exactly one matching receipt; got %', v_receipts; END IF;
END $$;

-- Re-running the helper must not duplicate the receipt.
SELECT public.post_finance_payment_journal_for_payment(1001);
DO $$
BEGIN
  IF (SELECT count(*) FROM public.finance_receipts WHERE payment_id = 1001) <> 1
    THEN RAISE EXCEPTION 'receipt creation is not idempotent'; END IF;
END $$;

