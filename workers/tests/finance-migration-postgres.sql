  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  school_id integer NOT NULL,
  invoice_id bigint NOT NULL,
  vote_head_id bigint,
  amount numeric(14,2) DEFAULT 0,
  balance numeric(14,2) DEFAULT 0
);
CREATE TABLE public.finance_vote_heads (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  school_id integer NOT NULL
);
CREATE TABLE public.payment_allocations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  school_id integer NOT NULL,
  payment_id bigint NOT NULL,
  invoice_id bigint,
  invoice_item_id bigint,
  vote_head_id bigint,
  amount numeric(14,2) NOT NULL CHECK (amount > 0),
  allocation_type text NOT NULL
    CONSTRAINT payment_allocations_type_check
    CHECK (allocation_type IN ('FEE','CREDIT','REVERSAL')),
  CONSTRAINT payment_allocations_allocation_type_check
    CHECK (allocation_type IN ('FEE','CREDIT','CREDIT_APPLIED','REVERSAL'))
);
CREATE TABLE public.finance_receipts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  receipt_number text,
  payment_id bigint,
  student_id bigint,
  amount numeric(14,2),
  issued_at timestamptz,
  status text,
  issued_by bigint
);
CREATE TABLE public.finance_journals (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  journal_date date,
  description text,
  reference text,
  status text,
  school_id integer NOT NULL,
  journal_number text
);
CREATE TABLE public.finance_journal_entries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  journal_id bigint NOT NULL,
  account_id bigint NOT NULL,
  debit numeric(14,2) NOT NULL DEFAULT 0,
  credit numeric(14,2) NOT NULL DEFAULT 0,
  description text
);

CREATE OR REPLACE FUNCTION public.ensure_finance_account(
  p_school_id integer, p_code text, p_name text, p_type text
) RETURNS bigint LANGUAGE plpgsql AS $$
BEGIN
  RETURN CASE p_code WHEN '1100' THEN 1100 WHEN '2000' THEN 2000
    WHEN '1010' THEN 1010 WHEN '1020' THEN 1020 ELSE 1000 END;
END;
$$;

-- Model the existing deferred payment trigger, whose function is replaced by
-- the posting migration below.
CREATE OR REPLACE FUNCTION public.post_finance_payment_journal()
RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END; $$;
CREATE CONSTRAINT TRIGGER trg_post_finance_payment_journal
AFTER INSERT ON public.payments
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION public.post_finance_payment_journal();

