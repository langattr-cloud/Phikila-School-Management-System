CREATE TABLE public.payments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  school_id integer NOT NULL,
  student_id bigint,
  invoice_id bigint,
  amount numeric(14,2),
  reversed boolean DEFAULT false,
  paid_at timestamptz,
  created_at timestamptz DEFAULT now(),
